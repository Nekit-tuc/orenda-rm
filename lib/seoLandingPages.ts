export function getSeoLandingPage(slug: string) {
  return seoLandingPages.find((page) => page.slug === slug) || null;
}

export function getSeoLandingRedirect(slug: string) {
  return seoLandingRedirects[slug] || null;
}

function normalizeText(value?: string | null) {
  return (value || "").toLowerCase();
}

function isZhytomyrProperty(property: FormattedProperty) {
  const address = normalizeText(property.address);
  const title = normalizeText(property.title);
  const locationText = `${title} ${address}`;

  return !excludedLocations.some((location) => locationText.includes(location));
}

function matchesDealType(property: FormattedProperty, dealType?: string) {
  if (!dealType) {
    return true;
  }

  return normalizeText(property.dealType) === normalizeText(dealType);
}

export function filterSeoLandingProperties(
  properties: FormattedProperty[],
  config: SeoLandingPageConfig,
) {
  return properties.filter((property) => {
    const typeMatch =
      config.objectTypes.length === 0 || config.objectTypes.includes(property.type);
    const dealMatch = matchesDealType(property, config.dealType);

    return typeMatch && dealMatch && isZhytomyrProperty(property);
  });
}
